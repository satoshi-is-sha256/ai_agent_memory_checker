#ifndef REPORT_H
#define REPORT_H

#include "common.h"
#include "timelinecorrelator.h"
#include <sstream>
#include <fstream>
#include <iomanip>
#include <chrono>
#include <set>

inline bool ExportMarkdownReport(const std::string &filePath, TimelineCorrelator &timeline) {
    std::ofstream outFile(filePath, std::ios::out | std::ios::trunc);
    if (!outFile.is_open()) return false;

    auto sortedEvents = timeline.GetSortedTimeline();

    std::set<std::string> uniqueNetworkEndpoints;
    std::set<std::string> uniquePipes;
    std::vector<TimelineCorrelator::TimelineEvent> spawnedProcesses;
    std::vector<TimelineCorrelator::TimelineEvent> detectedPayloads;

    for (const auto &ev : sortedEvents) {
        if (ev.category == TimelineCorrelator::TimelineCategory::Network) {
            uniqueNetworkEndpoints.insert(ev.details);
        }
        else if (ev.category == TimelineCorrelator::TimelineCategory::NamedPipe) {
            uniquePipes.insert(ev.details);
        }
        else if (ev.category == TimelineCorrelator::TimelineCategory::Alert) {
            spawnedProcesses.push_back(ev);
        }
        else if (ev.category == TimelineCorrelator::TimelineCategory::SharedMemory && ev.details.find("MOJO") != std::string::npos) {
            detectedPayloads.push_back(ev);
        }
    }

    auto now = std::chrono::system_clock::now();
    auto timeT = std::chrono::system_clock::to_time_t(now);
    std::tm tm{};
    localtime_s(&tm, &timeT);

    outFile << "# AI Agent Forensic Investigation Report\n\n";
    outFile << "- **Generated Date:** " << std::put_time(&tm, "%Y-%m-%d %H:%M:%S") << "\n";
    outFile << "- **Total Events Captured:** " << sortedEvents.size() << "\n\n";
    outFile << "---\n\n";

    outFile << "## 1. Executive Summary\n";
    outFile << "During the monitoring session, low-level system events were recorded to analyze autonomous background behavior, stealthy process spawning, and unprompted network bursts.\n\n";
    outFile << "- **Captured Network Destinations:** " << uniqueNetworkEndpoints.size() << " unique endpoints\n";
    outFile << "- **Active Named Pipes / Shared Memory:** " << uniquePipes.size() << " channels\n";
    outFile << "- **Process Sprout Intercepts:** " << spawnedProcesses.size() << " events\n";
    outFile << "- **Detected Payload Signatures:** " << detectedPayloads.size() << " items\n\n";

    outFile << "## 2. Intercepted Sub-process Spawns (`NtCreateUserProcess`)\n";
    if (spawnedProcesses.empty()) {
        outFile << "*No unauthorized process spawning detected during this session.*\n\n";
    }
    else {
        outFile << "| Timestamp | PID | Target Process / Command Line |\n";
        outFile << "| :--- | :--- | :--- |\n";
        for (const auto &proc : spawnedProcesses) {
            outFile << "| " << timeline.FormatEventToString(proc).substr(0, 12) << " | "
                    << proc.pid << " | `" << proc.details << "` |\n";
        }
        outFile << "\n";
    }

    outFile << "## 3. Detected Mojo IPC & JSON Payloads\n";
    if (detectedPayloads.empty()) {
        outFile << "*No structured JSON payloads or prompts flagged in memory buffers.*\n\n";
    }
    else {
        for (const auto& payload : detectedPayloads) {
            outFile << "```text\n";
            outFile << timeline.FormatEventToString(payload) << "\n";
            outFile << "```\n\n";
        }
    }

    outFile << "## 4. Chronological Event Timeline\n";
    outFile << "```text\n";
    for (const auto& ev : sortedEvents) {
        outFile << timeline.FormatEventToString(ev) << "\n";
    }
    outFile << "```\n\n";

    outFile << "---\n";
    outFile << "*Report automatically generated by AI Agent Memory Checker (v1.30 forensic suite).*\n";

    outFile.close();
    return true;
}

#endif
